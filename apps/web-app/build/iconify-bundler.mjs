import { readFileSync, readdirSync, statSync } from 'node:fs'
import { createRequire } from 'node:module'
import { extname, join } from 'node:path'

const require = createRequire(import.meta.url)

const ICON_STRING_RE = /['"]([a-z][a-z0-9-]{1,31}):([a-z0-9][a-z0-9-]{0,63})['"]/g
const SCAN_EXTS = new Set(['.vue', '.ts', '.tsx', '.js', '.jsx', '.mjs'])
const SKIP_DIRS = new Set(['node_modules', '.git', 'dist', '.vite', 'tests'])

const RESOLVE_ID = 'virtual:yinghuo-icons'
const VIRTUAL_ID = '\0' + RESOLVE_ID

function walkDir(root, onFile) {
  const stack = [root]
  while (stack.length) {
    const dir = stack.pop()
    let entries
    try {
      entries = readdirSync(dir)
    } catch {
      continue
    }
    for (const entry of entries) {
      const full = join(dir, entry)
      let st
      try {
        st = statSync(full)
      } catch {
        continue
      }
      if (st.isDirectory()) {
        if (SKIP_DIRS.has(entry)) continue
        stack.push(full)
      } else if (st.isFile() && SCAN_EXTS.has(extname(full))) {
        onFile(full)
      }
    }
  }
}

function collectUsedIcons(srcDir) {
  const used = new Map()
  walkDir(srcDir, (file) => {
    let src
    try {
      src = readFileSync(file, 'utf8')
    } catch {
      return
    }
    for (const m of src.matchAll(ICON_STRING_RE)) {
      const prefix = m[1]
      const name = m[2]
      let set = used.get(prefix)
      if (!set) {
        set = new Set()
        used.set(prefix, set)
      }
      set.add(name)
    }
  })
  return used
}

function loadIconifyJson(prefix) {
  try {
    const path = require.resolve(`@iconify-json/${prefix}/icons.json`)
    return require(path)
  } catch {
    return null
  }
}

function buildBundle(srcDir) {
  const used = collectUsedIcons(srcDir)
  const collections = []
  const warnings = []

  for (const [prefix, names] of used) {
    const fullSet = loadIconifyJson(prefix)
    if (!fullSet) continue

    const icons = {}
    const aliases = {}
    const found = []
    const missing = []

    const resolveAliasParent = (alias) => {
      let cur = alias
      const seen = new Set()
      while (fullSet.aliases && fullSet.aliases[cur]) {
        if (seen.has(cur)) return null
        seen.add(cur)
        cur = fullSet.aliases[cur].parent
        if (!cur) return null
      }
      return cur
    }

    for (const name of names) {
      if (icons[name] || aliases[name]) {
        found.push(name)
        continue
      }
      if (fullSet.icons[name]) {
        icons[name] = fullSet.icons[name]
        found.push(name)
        continue
      }
      if (fullSet.aliases && fullSet.aliases[name]) {
        const parent = resolveAliasParent(name)
        if (parent && fullSet.icons[parent]) {
          aliases[name] = fullSet.aliases[name]
          if (!icons[parent]) icons[parent] = fullSet.icons[parent]
          found.push(name)
        } else {
          missing.push(name)
        }
        continue
      }
      missing.push(name)
    }

    if (found.length === 0) {
      warnings.push(`[${prefix}] no icons resolved (scanned: ${[...names].join(', ')})`)
      continue
    }

    collections.push({
      prefix,
      icons,
      aliases: Object.keys(aliases).length ? aliases : undefined,
      width: fullSet.width,
      height: fullSet.height,
    })
    if (missing.length) {
      warnings.push(`[${prefix}] missing: ${missing.join(', ')}`)
    }
  }

  return { collections, warnings }
}

export function yinghuoIconifyBundler({ srcDir }) {
  let cache = null

  const getBundle = () => {
    if (!cache) cache = buildBundle(srcDir)
    return cache
  }

  return {
    name: 'yinghuo-iconify-bundler',
    enforce: 'pre',

    resolveId(id) {
      if (id === RESOLVE_ID) return VIRTUAL_ID
      return null
    },

    load(id) {
      if (id !== VIRTUAL_ID) return null
      const { collections, warnings } = getBundle()
      const summary = collections
        .map((c) => `${c.prefix}:${Object.keys(c.icons).length}`)
        .join(', ')
      const warnLines = warnings.length
        ? `console.warn('[iconify-bundler] bundled: ${summary}');\nconsole.warn('[iconify-bundler] warnings:\\n' + ${JSON.stringify(warnings.join('\n'))});`
        : `console.info('[iconify-bundler] bundled: ${summary}');`
      return [
        `// Auto-generated by build/iconify-bundler.mjs — do not edit.`,
        `// Scans apps/web-app/src for icon='prefix:name' patterns and bundles`,
        `// matching icons from @iconify-json/* packages so the app doesn't`,
        `// hit api.unisvg.com / api.iconify.design at runtime.`,
        `export const iconCollections = ${JSON.stringify(collections)};`,
        warnLines,
      ].join('\n')
    },

    configureServer(server) {
      const rebuild = (file) => {
        if (!file || !/\.(vue|ts|tsx|js|jsx|mjs)$/.test(file)) return
        cache = null
        const mod = server.moduleGraph.getModuleById(VIRTUAL_ID)
        if (mod) {
          server.reloadModule(mod).catch(() => {})
        }
      }
      server.watcher.on('change', rebuild)
      server.watcher.on('add', rebuild)
      server.watcher.on('unlink', rebuild)
    },
  }
}
